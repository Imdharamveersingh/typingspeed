/**
 * Returns a subset of the common word list based on size tier.
 * Small: ~100 top words
 * Medium: ~300 top words
 * Large: ~1,000 top words
 */
export function getWordListBySize(size: 'small' | 'medium' | 'large' = 'medium'): string[] {
  if (size === 'small') {
    return COMMON_PRACTICE_WORDS.slice(0, 100);
  }
  if (size === 'medium') {
    return COMMON_PRACTICE_WORDS.slice(0, 300);
  }
  return COMMON_PRACTICE_WORDS.slice(0, 1000);
}

/**
 * Computes exact stats (count, average word length) for a given word tier.
 */
export function getWordListStats(size: 'small' | 'medium' | 'large' = 'medium'): {
  count: number;
  avgLength: string;
} {
  const words = getWordListBySize(size);
  const count = words.length;
  const totalLength = words.reduce((acc, w) => acc + w.length, 0);
  const avgLength = count > 0 ? (totalLength / count).toFixed(1) : '0.0';
  return { count, avgLength };
}
